const src = readFileSync(join(ROOT, 'js', 'live-sim-data.js'), 'utf8');
const mod = { exports: {} };
new Function('module', 'exports', src + '\n;if(typeof LIVE_SIM_DATA!=="undefined")module.exports=LIVE_SIM_DATA;')(mod, mod.exports);
const D = mod.exports;

const groups = { start: START, middle: MIDDLE, end: END };
const XY = /XY/g, TEAM = /xy\s*\([^)]*\)/g, OPP = /yx\s*\([^)]*\)/g;
const cnt = (s, re) => (s.match(re) || []).length;

let errors = 0, warnings = 0;
const map = {};
for (const g of Object.keys(groups)) {
  const pt = groups[g], en = D.pieces[g];
  if (pt.length !== en.length) { console.error(`FATAL: ${g} has ${pt.length} Portuguese lines but ${en.length} English pieces`); process.exit(1); }
  en.forEach((p, i) => {
    const e = p.t, d = pt[i];
    if (!d) { console.error(`  ERROR ${g}[${i}] empty translation`); errors++; return; }
    // The dangerous case: Portuguese invents an XY the engine never bound -> literal "XY" on screen.
    if (cnt(e, XY) === 0 && cnt(d, XY) > 0) { console.error(`  ERROR ${g}[${i}] Portuguese has XY but English does not`); errors++; }
    if (cnt(e, XY) > 0 && cnt(d, XY) === 0) { console.warn(`  warn  ${g}[${i}] English names XY, Portuguese drops it`); warnings++; }
    if (cnt(e, TEAM) > 0 && cnt(d, TEAM) === 0) { console.warn(`  warn  ${g}[${i}] English has team token, Portuguese drops it`); warnings++; }
    if (cnt(e, OPP) > 0 && cnt(d, OPP) === 0) { console.warn(`  warn  ${g}[${i}] English has opp token, Portuguese drops it`); warnings++; }
    map[e] = d;
  });
}
if (errors) { console.error(`\n${errors} error(s) — not writing.`); process.exit(1); }

const header = `// GENERATED by scripts/gen-live-sim-pt.mjs — do not edit by hand.\n` +
  `// Portuguese overlay for the live-sim commentary, keyed by the EXACT English source string in\n` +
  `// js/live-sim-data.js. live-sim.js swaps these in when I18n.locale === 'pt'; any English line\n` +
  `// missing here falls back to English. Placeholders XY / "xy (player's team)" / "yx (opposition team)"\n` +
  `// are preserved so the engine's substitution still fires.\n`;
const body = `const LIVE_SIM_PT = ${JSON.stringify(map, null, 1)};\n` +
  `if (typeof module !== 'undefined' && module.exports) module.exports = { LIVE_SIM_PT };\n`;
writeFileSync(join(ROOT, 'js', 'live-sim-data-pt.js'), header + body);
